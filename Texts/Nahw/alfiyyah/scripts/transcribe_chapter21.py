#!/usr/bin/env python3
"""
transcribe_chapter21.py
Transcribes and formats Chapter 21: al-Tanazu' fi al-'Amal (Verses 278-285)
from PDF pages 196-201 with standardized formatting, Quranic links, and footnotes.
"""

import re
import os

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHARH_PATH = os.path.join(BASE_DIR, "Sharh/Sharh-alfiyyah-by-makhdumayn.md")

ch21_text = """
<a id="tanazu"></a>

## التنازع في العمل

وهو أن يتوجَّه عاملانِ إلى معمولٍ واحدٍ.

> **٢٧٨.** إِنْ عَامِلَانِ اقْتَضَيَا فِي اسْمِ عَمَلْ — قَبْلَ فَلِلْوَاحِدِ مِنْهُمَا الْعَمَلْ

(إنْ عاملانِ) أي فعلانِ أو ما جرى مجراهما (اقتضيا) أي طلبا (في اسمٍ) واحدٍ (عَمَلْ) وقف عليه بالسكون على لغة ربيعة (قبلُ) أي حال كونهما قبلَ الاسمِ كـ: قَامَ وَقَعَدَ زَيْدٌ (فللواحدِ منهما العملْ) في ذلك الاسم، والآخرُ يعمل في ضميره، نحو قوله تعالى: ﴿آتُونِي أُفْرِغْ عَلَيْهِ قِطْرًا﴾ [الكهف: ٩٦](https://quran.com/18/96)، وقوله تعالى: ﴿هَاؤُمُ اقْرَءُوا كِتَابِيَهْ﴾ [الحاقة: ١٩](https://quran.com/69/19)، وكقوله:

> عُهِدْتَ مُغِيثًا مَنْ أَجَرْتَ مِنَ الرَّدَى — وَمَأْوًى لِمَنْ أَمَّ الْفِنَاءَ وَمَوْئِلَا

[عُهِدْتَ: بالبناء للمفعول، أي عرفك الناسُ بإغاثة الملهوف، موئلًا: ملجأً من وأل إليه إذا لجأ. وخرج بقيد الاقتضاء العاملان المؤكَّد أحدُهما بالآخر نحو: أَتَاكَ أَتَاكَ اللَّاحِقُونَ احْبِسِ احْبِسِ، فلا تنازع بينهما].

> **٢٧٩.** وَالثَّانِ أَوْلَى عِنْدَ أَهْلِ الْبَصْرَةْ — وَاخْتَارَ عَكْسًا غَيْرُهُمْ ذَا أُسْرَهْ

(والثاني أولى) بالإعمال (عند أهل البصرة) لقربه من المعمول، نحو: قَامَا وَقَعَدَ أَخَوَاكَ، وضَرَبَانِي وَضَرَبْتُ الزَّيْدَيْنِ، وضَرَبْتُ وَضَرَبَنِي الزَّيْدُونَ (واختارَ عكسًا) وهو إعمال الأول (غيرُهم) وهم الكوفيون (ذا أُسْرَة) أي ذوو رهط وقوة؛ لسبقه، نحو: قَامَ وَقَعَدَا أَخَوَاكَ، وضَرَبْتُ وَضَرَبَانِي الزَّيْدَيْنِ.

> **٢٨٠.** وَأَعْمِلِ الْمُهْمَلَ فِي ضَمِيرِ مَا — تَنَازَعَاهُ، وَالْتَزِمْ مَا الْتَزَمَا

(وأَعْمِلِ المُهْمَلَ) وهو الذي لم يُسلَّط على الاسم الظاهر، سواء كان أولًا أو ثانيًا (في ضميرِ ما) أي الاسم الذي (تنازعاه) أي العاملان (والتزمْ ما التُزِما) من مطابقة الضمير للظاهر، وحذف الفضلة، وإثبات العمدة، ووجوب حذف الضمير في بعض الأحوال.

> **٢٨١.** كَـ(يُحْسِنَانِ وَيُسِيءُ ابْنَاكَا) — وَقَدْ بَغَى وَاعْتَدَيَا عَبْدَاكَا

(كـ: يُحْسِنَانِ وَيُسِيءُ ابْنَاكَا) بإضمار الفاعل في الأول مطابقًا للظاهر، ولا يجوز: «يُحْسِنُ وَيُسِيءُ ابْنَاكَ» بترك الإضمار، وكقول الشاعر:

> جَفَوْنِي وَلَمْ أَجْفُ الْأَخِلَّاءَ إِنَّنِي — لِغَيْرِ جَمِيلٍ مِنْ خَلِيلِيَ مُهْمِلُ

(وقد بَغَى وَاعْتَدَيَا عَبْدَاكَا) بإضمار الفاعل في الثاني إن أُعْمِلَ الأول، ولا يجوز تركُ إضماره أيضًا، فإن أُعْمِلَ الثاني قيل: «بَغَيَا وَاعْتَدَى عَبْدَاكَ».

> **٢٨٢.** وَلَا تَجِئْ مَعَ أَوَّلٍ قَدْ أُهْمِلَا — بِمُضْمَرٍ لِغَيْرِ رَفْعٍ أُهِّلَا

(ولا تَجِئْ مع) عاملٍ (أولٍ قد أُهْمِلَا) عن العمل (بمضمرٍ لغيرِ رفعٍ أُهِّلَا) أي لا تجئ في الأول المهمل بضمير جُعل أهلًا لغير الرفع، بأن احتاج لمنصوب لفظًا أو محلًّا.

> **٢٨٣.** بَلْ حَذْفَهُ الْزَمْ إِنْ يَكُنْ غَيْرَ خَبَرْ — وَأَخِّرَنَّهُ إِنْ يَكُنْ هُوَ الْخَبَرْ

(بل حذفَه الزمْ) لأنه فضلة (إنْ يكن غيرَ خبرٍ) كـ: ضَرَبْتُ وضَرَبَنِي زَيْدٌ، ومَرَرْتُ ومَرَّ بِي زَيْدٌ، بحذف مفعول الأول ومجروره، وقيل يجوز إضماره كقوله: «إِذَا كُنْتَ تُرْضِيهِ وَيُرْضِيكَ صَاحِبٌ» (وأَخِّرَنَّهُ إنْ يكن هو الخبرَ) بأن يكون العامل من باب كان أو ظن نحو: كُنْتُ وَكَانَ زَيْدٌ صَدِيقًا إِيَّاهُ، وظَنَّنِي وَظَنَنْتُ زَيْدًا قَائِمًا إِيَّاهُ، وقيل يُحذف في باب ظن وهو الصحيح؛ لأنه حذف لدليل.

> **٢٨٤.** وَأَظْهِرْ إِنْ يَكُنْ ضَمِيرَ خَبَرَا — لِغَيْرِ مَا يُطَابِقُ الْمُفَسِّرَا

(وأَظْهِرْ إنْ يكن ضميرَ خَبَرٍ لغيرِ ما يطابقُ المفسِّرا) يعني أن الضمير إذا كان خبرًا عن شيء مخالفٍ لمفسره في الإفراد والتذكير وفروعهما وجب إظهاره؛ لأنه إذا أُضمر موافقًا للمخبَر عنه خالف المفسِّر، وإن روعي المفسِّر خالف المخبَر عنه، فيتعين الإظهار دفعًا للبس.

> **٢٨٥.** نَحْوَ (أَظُنُّ وَيَظُنَّانِي أَخَا — زَيْدًا وَعَمْرًا أَخَوَيْنِ فِي الرَّخَا)

(نحو: أَظُنُّ وَيَظُنَّانِي أَخَا زَيْدًا وَعَمْرًا أَخَوَيْنِ فِي الرَّخَا) فـ: زيدًا وعمرًا: مفعول أول لأظن، وأخوين: مفعوله الثاني، والياء في يظناني: مفعول أول، و«أخا»: مفعول ثانٍ ظاهر، ولا يجوز إضماره لئلا يلتبس.
"""

def append_ch21():
    with open(SHARH_PATH, 'r', encoding='utf-8') as f:
        content = f.read()

    ref_marker = "\n---\n\n<a id=\"references\"></a>"
    if ref_marker not in content:
        print("ERROR: ref marker not found!")
        return

    # Update Phase notes in the header
    old_phase = "> **المرحلة الخامسة:** باب «اشتغال العامل عن المعمول» وباب «تعدي الفعل ولزومه» من البيت ٢٥٥ إلى تمام شرح البيت ٢٧٧، قبل باب «التنازع في العمل»."
    new_phase = """> **المرحلة الخامسة:** من باب «اشتغال العامل عن المعمول» إلى تمام باب «التنازع في العمل» من البيت ٢٥٥ إلى تمام شرح البيت ٢٨٥، قبل باب «المفعول المطلق»."""

    if old_phase in content:
        content = content.replace(old_phase, new_phase)

    # Update TOC table
    old_toc = "| ٢٥ | [تعدي الفعل ولزومه](#taaddi-luzum) |"
    new_toc = """| ٢٥ | [تعدي الفعل ولزومه](#taaddi-luzum) |
| ٢٦ | [التنازع في العمل](#tanazu) |"""

    if old_toc in content:
        content = content.replace(old_toc, new_toc)

    # Append Chapter 21 before references
    content = content.replace(ref_marker, ch21_text + ref_marker)

    with open(SHARH_PATH, 'w', encoding='utf-8') as f:
        f.write(content)

    print("Chapter 21 appended successfully!")

if __name__ == '__main__':
    append_ch21()
