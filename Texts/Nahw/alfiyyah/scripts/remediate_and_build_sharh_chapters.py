    text = text.replace("## النائب عن الفاعل", "## النَّائِبُ عَنِ الفَاعِلِ")
    text = text.replace("## اشتغال العامل عن المعمول", "## اشْتِغَالُ العَامِلِ عَنِ المَعْمُولِ")
