ch19_text = """
<a id="ishtighal"></a>

## اشتغال العامل عن المعمول

المرادُ بالعاملِ في هذا الباب: المفسِّرُ للعامِلِ في الاسم السابقِ، ومن شروطِه: صلاحيتُه للعملِ فيه، فوجبَ أن لا يكونَ إلا فعلًا متصرِّفًا أو اسمَ فاعلٍ أو اسمَ مفعولٍ، ولا يجوزُ أن يكونَ فعلًا غيرَ متصرفٍ، ولا صفةً مشبهةً، ولا حرفًا؛ لأنَّ هذه لا تعملُ فيما قبلها، فلا تُفَسِّرُ عاملًا فيه.

> **٢٥٥.** إِنْ مُضْمَرُ اسْمٍ سَابِقٍ فِعْلًا شَغَلْ — عَنْهُ بِنَصْبِ لَفْظِهِ أَوِ الْمَحَلْ

> **٢٥٦.** فَالسَّابِقَ انْصِبْهُ بِفِعْلٍ أُضْمِرَا — حَتْمًا مُوَافِقٍ لِمَا قَدْ أَظْهَرَا

(إنْ مضمرُ اسمٍ سابقٍ فعلًا شغَلْ) أي إن شغَلَ ضميرُ اسمٍ سابقٍ فعلًا متأخرًا (عنه) أي عن نصبِ لفظِ ذلك الاسمِ السابقِ (بنصبِ لفظِه) أي ضميرِه، كـ: زَيْدًا ضَرَبْتُهُ (أو المحلْ) أي بنصبِ محلِّه نحوُ: زَيْدًا مَرَرْتُ بِهِ؛ فكلُّ واحدٍ من ضَرَبْتُ و مَرَرْتُ قد اشتغلَ بضميرِ زيدٍ، لكن ضربْتُ وصلَ إلى الضميرِ بنفسِه، ومررْتُ وصلَ إليه بحرفِ جرٍّ، فهو مجرورٌ لفظًا ومنصوبٌ محلًّا، وكلٌّ من ضَرَبْتُ و مَرَرْتُ: لو لم يشتغلْ بالضميرِ لتسلَّطَ على زيدٍ كما تسلَّطَ على ضميرِه، فكنتَ تقولُ: زَيْدًا ضَرَبْتُ: فيصلُ الفعلُ إليه بنفسِه كما وصلَ إلى ضميرِه، وتقولُ: زَيْدًا مَرَرْتُ بِهِ: فيصلُ إلى زيدٍ بالباءِ كما وصلَ إلى ضميرِه به، ويكونُ منصوبًا محلًّا كما كان الضميرُ كذلك.

(فالسابقَ انصبْه) بفعلٍ مضمرٍ وجوبًا، فقوله: (بفعلٍ أُضمرا حتمًا) حالٌ من الضمير المستكنّ في انصبه (موافقٍ لما قد أظهرا) نعتٌ لـ: فعل، يعني: موافقٍ للفعلِ الظاهرِ إما في اللفظ والمعنى معًا نحوُ: زَيْدًا ضَرَبْتُهُ، فالتقديرُ: ضَرَبْتُ زَيْدًا ضَرَبْتُهُ، وإما في المعنى فقط دون اللفظ كـ: زَيْدًا مَرَرْتُ بِهِ، والتقديرُ: جاوَزْتُ زَيْدًا مَرَرْتُ بِهِ؛ لأنَّ مَرَرْتُ لا يصلُ إلى زيدٍ بنفسِه، وإنما يتعدى بالباءِ، فلا ينصبُ زيدًا، وإنما ينصبُه فعلٌ يتعدى بنفسِه موافقٌ لمرَرْتُ في المعنى، وهو جاوَزْتُ.

> **٢٥٧.** وَالنَّصْبُ حَتْمٌ إِنْ تَلَا السَّابِقَ مَا — يَخْتَصُّ بِالْفِعْلِ كَـ«إِنْ» وَحَيْثُمَا

(والنصبُ حتمٌ) أي واجبٌ، والاسمُ السابقُ له خمسةُ أحوالٍ: وجوبُ النصبِ، ورجحانُه، ووجوبُ الرفعِ، ورجحانُه، واستواءُ الأمرين. وقد بدأ بالحالةِ الأولى فقال: (إنْ تلا السابقُ ما يختصُّ بالفعلِ كـ: إنْ) من أدواتِ الشرطِ (وحيثما) من أسماءِ الشرط، وأدواتِ التحضيضِ، وأدواتِ الاستفهامِ غيرِ الهمزةِ، تقولُ: إِنْ زَيْدًا لَقِيتَهُ فَأَكْرِمْهُ، وحَيْثُمَا زَيْدًا تَلْقَهُ فَأَعِنْهُ، وهَلَّا زَيْدًا كَلَّمْتَهُ، ومَتَى زَيْدًا تَأْتِهِ.

> **٢٥٨.** وَإِنْ تَلَا السَّابِقَ مَا بِالِابْتِدَا — يَخْتَصُّ فَالرَّفْعَ الْتَزِمْهُ أَبَدَا

(وإنْ تلا السابقُ ما بالابتدا يختصُّ فالرفعَ التزمْه أبدًا) كـ: «إذا» الفجائية نحوُ: خَرَجْتُ فَإِذَا زَيْدٌ يَضْرِبُهُ عَمْرٌو، فيجبُ رفعُ «زيد» بالابتداء، ولا يجوزُ نصبُه بفعلٍ محذوفٍ؛ لأنَّ ما بعد إذا الفجائية لا يكونُ إلا جملةً اسمية، وكذلك إذا وقعَ بعد «ليتما» التي أُبطلَ عملُها بـ«ما»، ونحوُ: «لولا» الامتناعية نحوُ: لَوْلَا زَيْدٌ لَأَكْرَمْتُهُ.

[وفي بعض النسخ: «كذا إذا الفعلُ تلا ما لم يَرِدْ * ما قبلَه معمولَ ما بعدُ وُجِدْ»].

> **٢٥٩.** كَذَا إِذَا الْفِعْلُ تَلَا مَا لَمْ يُرَدْ — مَا قَبْلَهُ مَعْمُولَ مَا بَعْدَ وُجِدْ

(كذا) يلزمُ الرفعُ (إذا الفعلُ تلا) أي وقعَ بعد (ما لم يَرِدْ ما قبلَه معمولَ ما بعدُ) أي بعدَ ما له صدرُ الكلامِ، كأدواتِ الاستفهامِ، والشرطِ، وما النافية، ولامِ الابتداءِ، وإنَّ المشددةِ؛ نحوُ: زَيْدٌ هَلْ رَأَيْتَهُ؟ وزَيْدٌ مَا لَقِيتُهُ، وزَيْدٌ لَأَنَا ضَرَبْتُهُ؛ فلا يجوزُ في «زيد» إلا الرفعُ مبتدأً، لأنَّ ما بعدَ هذه الأدواتِ لا يعملُ فيما قبلَها، فلا يفسِّرُ عاملًا فيه.

> **٢٦٠.** وَاخْتِيرَ نَصْبٌ قَبْلَ فِعْلِ ذِي طَلَبْ — وَبَعْدَ مَا إِيلَاؤُهُ الْفِعْلَ غَلَبْ

(واختيرَ نصبٌ) في الاسم السابقِ، وذلك في مسائل: إحداها: أن يقعَ (قبلَ فعلٍ ذي طلبٍ) كالأمرِ والنهي والدعاء، نحوُ: زَيْدًا اضْرِبْهُ، وعَمْرًا لَا تُهِنْهُ، وخَالِدًا رَحِمَهُ اللّٰهُ؛ والنصبُ هنا أولى لئلا يُخبرَ بالجملةِ الطلبيةِ عن المبتدأ على خلافِ الأصلِ. والثانيةُ: أن يقعَ الاسمُ (بعدَ ما إيلاؤُه الفعلَ غلَبَ) أي بعد ما الغالبُ فيه أن يليه الفعلُ، كهمزةِ الاستفهامِ نحوُ: ﴿أَبَشَرًا مِنَّا وَاحِدًا نَتَّبِعُهُ﴾ [القمر: ٢٤](https://quran.com/54/24)، والهمزةُ وإن دخلت على الأسماءِ في نحو: «أزيدٌ قائمٌ؟» لكنَّ دخولَها على الأفعالِ أكثرُ.

> **٢٦١.** وَبَعْدَ عَاطِفٍ بِلَا فَصْلٍ عَلَى — مَعْمُولِ فِعْلٍ مُسْتَقِرٍّ أَوَّلَا

(وبعدَ عاطفٍ بلا فصلٍ على معمولِ فعلٍ مستقرٍّ أولًا) المسألةُ الثالثةُ من مسائلِ رجحانِ النصبِ: أن يقعَ الاسمُ السابقُ بعد حرفِ عطفٍ تقدمتْ عليه جملةٌ فعليةٌ نحوُ: قَامَ زَيْدٌ وَعَمْرًا أَكْرَمْتُهُ؛ فالنصبُ أرجحُ من الرفعِ؛ لعطفِ جملةٍ فعليةٍ على جملةٍ فعليةٍ، ومنه قولُه تعالى: ﴿خَلَقَ الْإِنْسَانَ مِنْ نُطْفَةٍ فَإِذَا هُوَ خَصِيمٌ مُبِينٌ * وَالْأَنْعَامَ خَلَقَهَا لَكُمْ﴾ [النحل: ٤-٥](https://quran.com/16/4-5) بنصبِ الأنعامِ في قراءةِ الجمهورِ.

> **٢٦٢.** وَإِنْ تَلَا الْمَعْطُوفُ فِعْلًا مُخْبِرَا — بِهِ عَنْ اسْمٍ فَاعْطِفَنْ مُخَيَّرَا

(وإنْ تلا المعطوفُ فعلًا مخبَرًا به عن اسمٍ) كقولِك: زَيْدٌ قَامَ أَبُوهُ وَعَمْرٌو أَكْرَمْتُهُ (فاعطِفَنْ مخيَّرًا) بين رفعِ «عمرو» ونصبِه؛ لاستواءِ الطرفين، فإن رفعتَه عطفتَ جملةً اسميةً على جملةٍ اسميةٍ كبرى (زيدٌ قام أبوه)، وإن نصبتَه عطفتَ جملةً فعليةً على جملةٍ فعليةٍ صغرى وهي جملةُ الخبرِ (قام أبوه).

> **٢٦٣.** وَالرَّفْعُ فِي غَيْرِ الَّذِي مَرَّ رُجِّحْ — فَمَا أُبِيحَ افْعَلْ، وَدَعْ مَا لَمْ يُبَحْ

(والرفعُ في غيرِ الذي مرَّ رُجِّحْ) أي إذا لم يكنْ هناك موجبٌ للنصبِ، ولا موجبٌ للرفعِ، ولا مرجِّحٌ للنصبِ، ولا مسوٍّ بينهما؛ فالرفعُ هو الأرجحُ، كقولك: زَيْدٌ ضَرَبْتُهُ، برفع «زيد» على الابتداء؛ لأنَّ الرفعَ لا يحتاجُ إلى تقديرٍ، بخلافِ النصبِ فإنه يحتاجُ إلى إضمارِ فعلٍ عاملٍ، وعدمُ التقديرِ أرجحُ من التقديرِ. (فما أُبيحَ افعلْ ودعْ ما لم يُبَحْ).

> **٢٦٤.** وَفَصْلًا مَشْغُولٍ بِحَرْفِ جَرِّ — أَوْ بِإِضَافَةٍ كَوَصْلٍ يَجْرِي

(وفصلُ مشغولٍ بحرفِ جرٍّ أو بالإضافةِ كوصلٍ يجري) يعني أنَّ المشغولَ به إذا انفصلَ عن الفعلِ بحرفِ جرٍّ نحوُ: زَيْدًا مَرَرْتُ بِهِ، أو بالإضافةِ نحوُ: زَيْدًا ضَرَبْتُ غُلَامَهُ، أو: زَيْدًا مَرَرْتُ بِغُلَامِهِ؛ يجري مجرى المتصلِ به بنفسِه نحوُ: زَيْدًا ضَرَبْتُهُ، في جميعِ الأحكامِ المتقدمةِ من وجوبِ النصبِ، ورجحانِه، واستواءِ الأمرين، ورجحانِ الرفعِ.

> **٢٦٥.** وَسَبْقُ فِي ذَا الْبَابِ وَصْفًا ذَا عَمَلْ — بِالْفِعْلِ؛ إِنْ لَمْ يَكُ مَانِعٌ حَصَلْ

(وسوِّ في ذا البابِ وصفًا ذا عملْ بالفعلِ) يعني أنَّ اسمَ الفاعلِ واسمَ المفعولِ يعملانِ في هذا البابِ عملَ الفعلِ بشرطِ أن يكونا عاملين نحوُ: زَيْدًا أَنَا ضَارِبُهُ، والتقديرُ: أَنَا ضَارِبٌ زَيْدًا أَنَا ضَارِبُهُ، (إنْ لم يكُ مانعٌ حصلْ) كأن يكونَ الوصفُ صلةً لأل، نحوُ: زَيْدٌ أَنَا الضَّارِبُهُ، فلا يجوزُ النصبُ؛ لأنَّ صلةَ أل لا تعملُ فيما قبلها.

> **٢٦٦.** وَعَلْقَةٌ حَاصِلَةٌ بِتَابِعِ — كَعَلْقَةٍ بِنَفْسِ الِاسْمِ الْوَاقِعِ

(وعَلَقَةٌ حاصلةٌ بتابعٍ كعَلَقَةٍ بنفسِ الاسمِ الواقعِ) يعني أنَّ العلقةَ التي تحصلُ بملابسةِ الضميرِ المشغولِ به، تحصلُ أيضًا بملابسةِ التابعِ لاسمٍ مشتملٍ على ضميرِ الاسمِ السابقِ، نحوُ: زَيْدًا ضَرَبْتُ رَجُلًا يُحِبُّهُ؛ فالضميرُ في «يحبُّه» عائدٌ إلى زيدٍ، والفعلُ «ضربْتُ» مشغولٌ برجلٍ، ورجلٌ موصوفٌ بجملةِ يحبُّه، فكأنَّ الفعلَ مشغولٌ بسببيِّ زيدٍ، فيجري عليه حكمُ البابِ.
"""

def append_ch19():
    with open(SHARH_PATH, 'r', encoding='utf-8') as f:
        content = f.read()

    ref_marker = "\n---\n\n<a id=\"references\"></a>"
    if ref_marker not in content:
        print("ERROR: ref marker not found!")
        return

    # Update Phase notes in the header
    old_phase = "> **المرحلة الرابعة:** باب «النائب عن الفاعل» من البيت ٢٤٢ إلى تمام شرح البيت ٢٥٤، قبل باب «اشتغال العامل عن المعمول»."
    new_phase = """> **المرحلة الرابعة:** باب «النائب عن الفاعل» من البيت ٢٤٢ إلى تمام شرح البيت ٢٥٤.  
> **المرحلة الخامسة:** باب «اشتغال العامل عن المعمول» من البيت ٢٥٥ إلى تمام شرح البيت ٢٦٦، قبل باب «تعدي الفعل ولزومه»."""

    if old_phase in content:
        content = content.replace(old_phase, new_phase)

    # Update TOC table
    old_toc = "| ٢٣ | [النائب عن الفاعل](#naib-fail) |"
    new_toc = """| ٢٣ | [النائب عن الفاعل](#naib-fail) |
| ٢٤ | [اشتغال العامل عن المعمول](#ishtighal) |"""

    if old_toc in content:
        content = content.replace(old_toc, new_toc)

    # Append Chapter 19 before references
    content = content.replace(ref_marker, ch19_text + ref_marker)

    with open(SHARH_PATH, 'w', encoding='utf-8') as f:
        f.write(content)

    print("Chapter 19 appended successfully!")

if __name__ == '__main__':
    append_ch19()
