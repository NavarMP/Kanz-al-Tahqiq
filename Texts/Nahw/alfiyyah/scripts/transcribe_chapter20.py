#!/usr/bin/env python3
"""
transcribe_chapter20.py
Transcribes and formats Chapter 20: Ta'addi al-Fi'l wa-Luzumuh (Verses 267-277)
from PDF pages 190-196 with standardized formatting, Quranic links, and footnotes.
"""

import re
import os

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHARH_PATH = os.path.join(BASE_DIR, "Sharh/Sharh-alfiyyah-by-makhdumayn.md")

ch20_text = """
<a id="taaddi-luzum"></a>

## تعدّي الفعل ولزومه

> **٢٦٧.** علامةُ الفعلِ المُعَدَّى أن تصلَ — ها غيرَ مصدرٍ به نحوَ «عملْ»

(علامةُ الفعلِ المعدَّى أن تصلَ ها غيرَ مصدرٍ به) أي بذلك الفعلِ بنفسِه دونَ حرفِ جرٍّ، وهي هاءُ المفعولِ به، واحترزَ بها عن هاءِ المصدرِ فإنها تتصلُ بالمتعدي واللازمِ، نحوُ: ضَرَبْتُهُ زَيْدًا، أي: ضربتُ الضربَ زيدًا، أو: قُمْتُهُ، أي: قمتُ القيامَ. وللمتعدي علامةٌ أخرى: وهي أن يُبنى منه اسمُ مفعولٍ تامٌّ كـ: مضروب في ضَرَبَ. (نحوُ: عَمِلْ) فإنه يتصلُ إليه مفعولُه، كقولِك: الخَيْرُ عَمِلَهُ زَيْدٌ، وزَيْدٌ ضَرَبَهُ عَمْرٌو.

> **٢٦٨.** فانصبْ به مفعولَه إن لم يَنُبْ — عن فاعلٍ نحوَ «تدبَّرتُ الكتبْ»

(فانصبْ به) أي بالفعلِ المتعدي (مفعولَه إن لم ينبْ عن فاعلٍ نحوُ: تَدَبَّرْتُ الْكُتُبْ) فإن نابَ عن الفاعلِ وجبَ رفعُه كما تقدمَ نحوُ: تُدُبِّرَتِ الْكُتُبُ. وقد يُرفعُ المفعولُ به ويُنصبُ الفاعلُ عند أمنِ اللبسِ كقولِهم: «خَرَقَ الثَّوْبُ الْمِسْمَارَ»، ولا يُقاسُ على ذلك بل يُقتصرُ على السماعِ.

> **٢٦٩.** ولازمٌ غيرُ المُعَدَّى، وحُتِمْ — لزومُ أفعالِ السجايا كـ«نَهِمْ»

(ولازمٌ غيرُ المعدَّى) وهو ما لا يتصلُ به هاءُ غيرِ المصدرِ، كـ: قَعَدَ، وقَامَ، وطَالَ، وكَرُمَ (وحُتِمَ لزومُ أفعالِ السجايا) أي الطبائعِ التي لا تتنقلُ (كـ: نَهِمَ) بكسر الهاء، وشَرِهَ، وفَرِحَ، وحَزِنَ، وجَبُنَ، وشَجُعَ.

> **٢٧٠.** كذا «افعلْ»، والمضاهي «انفعنسا» — وما اقتضى نظافةً أو دَنَسا

(كذا افعلَلَّ) بفتح اللام الأولى وتشديد الثانية نحوُ: اقْشَعَرَّ واطْمَأَنَّ، وافْعَلَلَ نحوُ: احْرَنْجَمَ (والمضاهي انْفَعَنْسَسَ) نحوُ: اقْعَنْسَسَ وافْعَنْلَلَ نحوُ: احْرَنْجَمَ (وما اقتضى نظافةً) كـ: طَهُرَ الثَّوْبُ، ونَظُفَ، وَوَضُؤَ (أو دَنَسًا) نحوُ: دَنِسَ الثَّوْبُ، وقَذِرَ، ووَسِخَ.

> **٢٧١.** أو عرضًا، أو طاوعَ المُعَدَّى — لواحدٍ كـ«مدَّهُ فامتدَّا»

(أو عَرَضًا) أي أمرًا غيرَ لازمٍ، نحوُ: مَرِضَ زَيْدٌ، وكَسِلَ، ونَشِطَ (أو طاوعَ المعدَّى لواحدٍ) كـ: كَسَرْتُ الزُّجَاجَ فَانْكَسَرَ، و(مَدَدْتُهُ فَامْتَدَّ)، ودَحْرَجْتُهُ فَتَدَحْرَجَ؛ فإن طاوعَ ما يتعدى لاثنين لم يكن لازمًا، بل يكون متعديًا لواحد كـ: عَلَّمْتُهُ الْقُرْآنَ فَتَعَلَّمَهُ.

> **٢٧٢.** ووُعِدَ لازمًا بحرفِ جرٍّ — وإن حُذِفَ فالنصبُ للمُنْجَرِّ

(وعُدِّيَ لازمٌ بحرفِ جرٍّ) يعني أنَّ الفعلَ اللازمَ يتعدى إلى المفعولِ بحرفِ الجرِّ نحوُ: مَرَرْتُ بِزَيْدٍ، وغَضِبْتُ عَلَيْهِ (وإنْ حُذِفَ) حرفُ الجرِّ من المجرورِ (فالنصبُ للمُنْجَرِّ) به، أي لذلك الاسمِ الذي كان مجرورًا به.

> **٢٧٣.** نقلًا، وفي «أنْ» و«أنَّ» يطَّرِدْ — مع أمنِ لبسٍ كـ«عجبتُ أنْ يَدُوا»

وحذفُ حرفِ الجرِّ مع غيرِ «أنْ» و«أنَّ»: (نقلًا) أي سماعًا، لا يجوزُ القياسُ عليه، كقولِهم: «تَمْرًا وَدَقَلًا» أي: أترغبُ في تمرٍ ودقلٍ؟ وقولِ الشاعر: «تَمُرُّونَ الدِّيَارَ» أي بالديارِ. (وفي أنْ وأنَّ يطَّرِدْ مع أمنِ لبْسٍ كـ: عَجِبْتُ أَنْ يَدُوا) أي من أن يَدُوا، أي يُعطوا الديةَ، وقولِه تعالى: ﴿شَهِدَ اللَّهُ أَنَّهُ لَا إِلَهَ إِلَّا هُوَ﴾ [آل عمران: ١٨](https://quran.com/3/18) أي بأنه، وقولِه تعالى: ﴿أَوَعَجِبْتُمْ أَنْ جَاءَكُمْ ذِكْرٌ مِنْ رَبِّكُمْ﴾ [الأعراف: ٦٣](https://quran.com/7/63) أي من أن جاءكم، فإن خِيفَ اللبسُ لم يجزْ نحوُ: رَغِبْتُ فِي أَنْ تَقُومَ، لئلا يلتبسَ بـ: رغبتُ عن أن تقومَ.

> **٢٧٤.** والأصلُ سبقُ فاعلٍ معنىً كـ«مَنْ» — من «البِسْنَ من زاركم نسجَ اليمنْ»

(والأصلُ) فيما يتعدى إلى مفعولين ليس أصلُهما مبتدأً وخبرًا، كبابِ كسا وأعطى (سبقُ فاعلٍ معنىً) وهو المفعولُ الأول؛ لأنه الآخِذُ والفاعلُ في المعنى، نحوُ: أَعْطَيْتُ زَيْدًا دِرْهَمًا، فـ: زيد: فاعلٌ في المعنى؛ لأنه الآخذُ للدرهمِ، ومنه: (أَلْبِسْنَ مَنْ زَارَكُمْ نَسْجَ الْيَمَنْ) فـ: «مَنْ»: هو الآخذُ، فهو المفعولُ الأولُ.

> **٢٧٥.** ويلزمُ الأصلُ لموجبٍ عرا — وتركُ ذاك الأصلِ حتمًا قد يُرى

(ويلزمُ الأصلُ) من تقديمِ ما هو فاعلٌ في المعنى (لموجبٍ عَرَا) أي عَرَضَ، كأنْ يخافَ اللبسُ نحوُ: أَعْطَيْتُ زَيْدًا عَمْرًا، فيتعينُ تقديمُ زيدٍ؛ لأنه الآخذُ؛ أو يكونَ المفعولُ الأولُ ضميرًا متصلًا نحوُ: أَعْطَيْتُكَهُ، (وتركُ ذاك الأصلِ حتمًا قد يُرى) في مسائل: منها: أن يشتملَ المفعولُ الأولُ على ضميرٍ يعودُ على الثاني نحوُ: أَعْطَيْتُ الدِّرْهَمَ صَاحِبَهُ، ومنها: أن ينحصرَ المفعولُ الأولُ نحوُ: مَا أَعْطَيْتُ الدِّرْهَمَ إِلَّا زَيْدًا.

> **٢٧٦.** وحذفُ فضلةٍ أجزْ إن لم يضرَّ — كحذفِ ما سبقَ جوابًا أو حصرْ

(وحذفُ فضلةٍ أَجِزْ إنْ لم يضرَّ) أي يجوزُ حذفُ الفضلةِ، وهي المفعولُ به، إن لم يضرَّ حذفُه كقولِك: ضَرَبْتُ، وأَكَلْتُ، أي شيئًا، وقولِه تعالى: ﴿فَأَمَّا مَنْ أَعْطَى وَاتَّقَى﴾ [الليل: ٥](https://quran.com/92/5) أي أعطى المالَ؛ فإن أضرَّ حذفُه لم يجزْ، (كحذفِ ما سِيقَ جوابًا) نحوُ أن يُقالَ: من ضربتَ؟ فلا يجوزُ أن تقولَ: ضربتُ وتسكت، (أو حُصِرَ) بـ«إلا» أو «إنما» نحوُ: مَا ضَرَبْتُ إِلَّا زَيْدًا، فلا يجوزُ حذفُ زيدٍ.

> **٢٧٧.** ويُحذفُ النائبُها إن عُلِما — وقد يكونُ حذفُه ملتزمًا

(ويُحذفُ الناصبُها) أي ناصبُ الفضلةِ جوازًا (إن عُلِمَا) كقولِك لمن سدَّدَ سهمًا: «الْقِرْطَاسَ»، ولمن تأهبَ لسفرٍ: «مَكَّةَ»، ولمن قالَ: من أضربُ؟: «شَرَّ النَّاسِ»، بإضمارِ: تُصِيبُ، وتُرِيدُ، واضْرِبْ. (وقد يكونُ حذفُه ملتزمًا) كما في بابِ الاشتغالِ نحوُ: زَيْدًا ضَرَبْتُهُ، وبابِ النداءِ نحوُ: يَا عَبْدَ اللّٰهِ، والتحذيرِ بـ«إياك» نحوُ: إِيَّاكَ وَالْأَسَدَ.
"""

def append_ch20():
    with open(SHARH_PATH, 'r', encoding='utf-8') as f:
        content = f.read()

    ref_marker = "\n---\n\n<a id=\"references\"></a>"
    if ref_marker not in content:
        print("ERROR: ref marker not found!")
        return

    # Update Phase notes in the header
    old_phase = "> **المرحلة الخامسة:** باب «اشتغال العامل عن المعمول» من البيت ٢٥٥ إلى تمام شرح البيت ٢٦٦، قبل باب «تعدي الفعل ولزومه»."
    new_phase = """> **المرحلة الخامسة:** باب «اشتغال العامل عن المعمول» وباب «تعدي الفعل ولزومه» من البيت ٢٥٥ إلى تمام شرح البيت ٢٧٧، قبل باب «التنازع في العمل»."""

    if old_phase in content:
        content = content.replace(old_phase, new_phase)

    # Update TOC table
    old_toc = "| ٢٤ | [اشتغال العامل عن المعمول](#ishtighal) |"
    new_toc = """| ٢٤ | [اشتغال العامل عن المعمول](#ishtighal) |
| ٢٥ | [تعدي الفعل ولزومه](#taaddi-luzum) |"""

    if old_toc in content:
        content = content.replace(old_toc, new_toc)

    # Append Chapter 20 before references
    content = content.replace(ref_marker, ch20_text + ref_marker)

    with open(SHARH_PATH, 'w', encoding='utf-8') as f:
        f.write(content)

    print("Chapter 20 appended successfully!")

if __name__ == '__main__':
    append_ch20()
