AR_DIGITS = '٠١٢٣٤٥٦٧٨٩'
def ar_to_int(s):
    val = 0
    for ch in s:
        if ch in AR_DIGITS: val = val * 10 + AR_DIGITS.index(ch)
        elif ch.isdigit(): val = val * 10 + int(ch)
    return val

def standardize_quran_links(text):
    # Matches patterns like: [البقرة: ١٩٦] not followed by (https://quran.com...)
    def repl(m):
        full = m.group(0)
        surah = m.group(1).strip()
        ayah_str = m.group(2).strip()
        
        # Check if already followed by url
        end_pos = m.end()
        if text[end_pos:end_pos+4] == '(htt':
            return full
            
        surah_id = SURAH_NAMES.get(surah)
        if not surah_id:
            # try fuzzy or partial
            for k, v in SURAH_NAMES.items():
                if k in surah or surah in k:
                    surah_id = v
                    break
                    
        if surah_id:
            ayah_id = ar_to_int(ayah_str)
            return f"[{surah}: {ayah_str}](https://quran.com/{surah_id}/{ayah_id})"
        return full

    return re.sub(r'\[([^\:\]]+)\:\s*([٠-٩\d]+)\]', repl, text)

