def main():
    with open(MATN_PATH, 'r', encoding='utf-8') as f:
        matn = f.read()

    blocks = re.split(r'\n(?=##\s+\d+\.)', matn)
    chap_blocks = blocks[1:]

    out = []
    out.append("""<div dir="rtl" lang="ar" style="direction: rtl; text-align: right;">

# حَلُّ الْمَنْظُومِ وَنَثْرُ الأَلْفِيَّةِ مَعَ التَّقْدِيرِ النَّحْوِيِّ
## Prose Paraphrase and Syntactic Reconstruction of Alfiyyah Ibn Malik

> **المصنف الأساس:** ألفية الإمام أبي عبد الله محمد جمال الدين بن مالك الأندلسي الجياني (ت ٦٧٢ هـ).  
> **المنهج والغاية:** فك التعقيد اللفظي والتقديم والتأخير الناشئ عن ضرورة وزن بحر الرجز وقافيته، وإظهار المحذوفات والمقدرات النحوية، وإعادة صياغة كل بيت في صورة جملة نثرية تركيبية فصيحة، تيسيرًا لمدارسة المتن النحوي وفهم إشاراته.

---

## الفهرس العام للأبواب

| الرقم | الباب النحوي | عدد الأبيات |
|:---:|:---|:---:|""")

    # Build TOC
    chap_data = []
    for b in chap_blocks:
        lines = b.strip().split('\n')
        m = re.match(r'##\s+(\d+)\.\s*(.+)', lines[0])
        num = int(m.group(1))
        name = m.group(2).strip()
        verses = [l.strip() for l in lines[1:] if re.match(r'^\*\*\d+\.\*\*', l.strip())]
        chap_data.append((num, name, verses))
        out.append(f"| {num:02d} | [{name}](#chap-{num}) | {len(verses)} |")

    out.append("\n---\n")

    # Build each chapter
    for num, name, verses in chap_data:
        out.append(f"""\n<a id="chap-{num}"></a>\n## {num}. {name}\n""")
        for v in verses:
            vm = re.match(r'^\*\*(\d+)\.\*\*\s*(.+)', v)
            v_num = int(vm.group(1))
            v_text = vm.group(2).strip()
            nasr, irab = get_nasr_for_verse(v_num, v_text)
            
            out.append(f"""### البيت {v_num}

> **{v_num}.** {v_text}

* **نثر البيت (حل المنظوم):** {nasr}
* **التقدير والإعراب الإجمالي:** {irab}
""")

    out.append("""\n---\n\n### المصادر والمراجع المرتبطة
- [المتن الأصلي لألفية ابن مالك](alfiyyah-ibn-malik.md)
- [شرح الخلاصة الألفية للشيخين المخدومين](Sharh/Sharh-alfiyyah-by-makhdumayn.md)
- [അൽഫിയ്യ: മലയാള വിവർത്തനവും വ്യാഖ്യാനവും](alfiyyah-ibn-malik-ml.md)
- [فهرس مجلد الأبواب المستقلة](chapters/README.md)
- [الجامع الموسوعي للألفية](alfiyyah-al-jami.md)

</div>
""")

    with open(OUTPUT_PATH, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out))

    print(f"Successfully generated {OUTPUT_PATH} with {len(chap_data)} chapters.")

if __name__ == '__main__':
    main()
